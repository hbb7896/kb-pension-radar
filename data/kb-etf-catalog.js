// 퇴직연금 거래 불가 종목 필터 (레버리지, 인버스, 곱버스, VIX, 고위험 선물 등)
function isPensionEligible(itemName) {
  if (!itemName) return false;
  const bannedKeywords = [
    "레버리지", "인버스", "2X", "선물인버스", "곱버스",
    "VIX", "블룸버그2X", "코스닥150선물", "원유선물", "천연가스선물", "농산물선물", "구리선물"
  ];
  for (const kw of bannedKeywords) {
    if (itemName.includes(kw)) return false;
  }
  return true;
}

// KB국민은행 퇴직연금 입점 주요 운용사 브랜드 추출
function detectManager(itemName) {
  const n = (itemName || "").toUpperCase();
  if (n.startsWith("RISE ") || n.startsWith("KBSTAR ")) return "RISE";
  if (n.startsWith("TIGER ")) return "TIGER";
  if (n.startsWith("KODEX ")) return "KODEX";
  if (n.startsWith("ACE ") || n.startsWith("KINDEX ")) return "ACE";
  if (n.startsWith("SOL ")) return "SOL";
  if (n.startsWith("PLUS ") || n.startsWith("ARIRANG ")) return "PLUS";
  if (n.startsWith("HANARO ")) return "HANARO";
  if (n.startsWith("KOSEF ") || n.startsWith("KIWOOM ") || n.startsWith("히어로즈 ")) return "KOSEF";
  if (n.startsWith("TIMEFOLIO ")) return "TIMEFOLIO";
  if (n.startsWith("WON ")) return "WON";
  if (n.startsWith("1Q ")) return "1Q";
  return "OTHER";
}

// 종목명 기반 안전자산(100%) vs 위험자산(70%) 자동 판별
function detectAssetClass(itemName, tabCode) {
  const n = itemName || "";
  if (
    n.includes("채권") ||
    n.includes("국고채") ||
    n.includes("국채") ||
    n.includes("통안채") ||
    n.includes("회사채") ||
    n.includes("단기채") ||
    n.includes("종합채") ||
    n.includes("머니마켓") ||
    n.includes("CD금리") ||
    n.includes("CD1년") ||
    n.includes("KOFR") ||
    n.includes("TDF") ||
    n.includes("자산배분") ||
    n.includes("채권혼합") ||
    n.includes("미국채혼합") ||
    tabCode === 5 || tabCode === 6 // 네이버 금융 ETF 탭 코드 (채권/기타)
  ) {
    return "SAFE";
  }
  return "RISK";
}

// 종목명 기반 세부 카테고리 자동 분류
